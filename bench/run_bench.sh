#!/usr/bin/env bash
#
# Measure the runtime and memory overhead of ASan, following the methodology of
# Figure 2 and Table 1 in the paper.
#
# Three configurations are compared:
#   base         baseline: -O2, no instrumentation
#   asan_default instrumented: -O2 + ASan, default runtime settings (quarantine 256MB,
#                redzone 128B)
#   asan_paper   instrumented + the measurement settings of paper section 4
#                (quarantine 0, redzone 32B, no malloc stack unwinding)
#
# Paper section 4: "We used 32-byte red zones, disabled the stack unwinding during
# malloc and free and set the quarantine size to zero". Without following this, the
# ratio of a malloc-heavy workload is inflated by an order of magnitude by the
# 256MB quarantine and is not comparable with the paper at all.
#
# Statistics follow the course requirements: REPEAT (>=3) runs per configuration,
# reported as mean and standard deviation. Every individual run is written to
# docs/measured/raw_runs.tsv so that the numbers in the report are traceable.
#
# Usage: bash bench/run_bench.sh
# Output: docs/measured/performance.md, docs/measured/raw_runs.tsv

set -u

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BIN_DIR="$ROOT_DIR/build"
OUT="$ROOT_DIR/docs/measured/performance.md"
RAW="$ROOT_DIR/docs/measured/raw_runs.tsv"
REPEAT="${REPEAT:-5}"
CC="${CC:-gcc}"

MODES="malloc_heavy access_heavy mixed"
CFLAGS_BASE="-std=c11 -O2 -g -fno-omit-frame-pointer"
CFLAGS_ASAN="$CFLAGS_BASE -fsanitize=address"
PAPER_OPTS="quarantine_size_mb=0:redzone=32:malloc_context_size=0"

mkdir -p "$BIN_DIR" "$(dirname "$OUT")"

$CC $CFLAGS_BASE bench/bench.c -o "$BIN_DIR/bench_base" || exit 1
$CC $CFLAGS_ASAN bench/bench.c -o "$BIN_DIR/bench_asan" || exit 1

# Binary size (matches the 1.5x-3.2x, 2.5x average quoted in paper section 4)
sz_base=$(stat -c%s "$BIN_DIR/bench_base" 2>/dev/null || echo 0)
sz_asan=$(stat -c%s "$BIN_DIR/bench_asan" 2>/dev/null || echo 0)
sz_ratio=$(awk -v a="$sz_asan" -v b="$sz_base" 'BEGIN{printf "%.2f", (b>0)?a/b:0}')

printf 'mode\tconfig\trun\ttime_ms\tvmhwm_kb\tvmpeak_kb\tvmstk_kb\n' > "$RAW"

# Run one configuration REPEAT times, appending every raw sample
one_run() {
    local bin="$1" mode="$2" cfg="$3" opts="${4:-}" i out
    for i in $(seq 1 "$REPEAT"); do
        if [ -n "$opts" ]; then
            out=$(ASAN_OPTIONS="$opts" "$bin" "$mode" 2>/dev/null | grep '^RESULT' | tail -1)
        else
            out=$("$bin" "$mode" 2>/dev/null | grep '^RESULT' | tail -1)
        fi
        printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
            "$mode" "$cfg" "$i" \
            "$(echo "$out" | sed -n 's/.*time_ms=\([0-9.]*\).*/\1/p')" \
            "$(echo "$out" | sed -n 's/.*vmhwm_kb=\([0-9-]*\).*/\1/p')" \
            "$(echo "$out" | sed -n 's/.*vmpeak_kb=\([0-9-]*\).*/\1/p')" \
            "$(echo "$out" | sed -n 's/.*vmstk_kb=\([0-9-]*\).*/\1/p')" >> "$RAW"
    done
}

# stats <mode> <config> <column>
# Prints "mean std": the sample standard deviation between runs (n-1)
stats() {
    awk -F'\t' -v m="$1" -v c="$2" -v col="$3" '
        $1==m && $2==c && $col!="" {
            n++; v[n]=$col+0; s+=$col+0
        }
        END {
            if (n==0) { print "0.00 0.00"; exit }
            mean=s/n
            ss=0
            if (n>1) {
                for (i=1;i<=n;i++) { d=v[i]-mean; ss+=d*d }
                sd=sqrt(ss/(n-1))
            } else {
                sd=0
            }
            printf "%.2f %.2f\n", mean, sd
        }' "$RAW"
}

cv() { awk -v m="$1" -v s="$2" 'BEGIN{printf "%.1f", (m>0)?100*s/m:0}'; }
ratio() { awk -v a="$1" -v b="$2" 'BEGIN{printf "%.2f", (b>0)?a/b:0}'; }

cpu_model=$(lscpu 2>/dev/null | grep -m1 'Model name' | cut -d: -f2- | sed 's/^ *//')
cpu_model=${cpu_model:-?}

for mode in $MODES; do
    one_run "$BIN_DIR/bench_base" "$mode" "base" ""
    one_run "$BIN_DIR/bench_asan" "$mode" "asan_default" ""
    one_run "$BIN_DIR/bench_asan" "$mode" "asan_paper" "$PAPER_OPTS"
done

{
    echo "# Overhead measurement results"
    echo
    echo "Reproduction target: **Figure 2** of the paper (runtime overhead, 1.73x on"
    echo "average) and **Table 1** (memory overhead, 3.37x on average)."
    echo "This file is generated by \`bench/run_bench.sh\` on a real machine; it is not a"
    echo "set of expected values. The raw numbers of every run are in"
    echo "\`docs/measured/raw_runs.tsv\`."
    echo
    echo "- Generated at (UTC): \`$(date -u '+%Y-%m-%d %H:%M:%S')\`"
    echo "- CPU: \`$cpu_model\`"
    echo "- Kernel: \`$(uname -r)\`"
    echo "- Compiler: \`$($CC --version | head -1)\`"
    echo "- Runs: $REPEAT per configuration, reported as mean and standard deviation (sample, n-1)"
    echo "- commit: \`$(git -C "$ROOT_DIR" rev-parse --short HEAD 2>/dev/null || echo '?')\`"
    echo
    echo "Configurations: **base** = uninstrumented baseline; **asan_default** = default"
    echo "ASan settings; **asan_paper** = ASan with the measurement settings of paper"
    echo "section 4 (\`$PAPER_OPTS\`)."
    echo
    echo "## Table 1  Runtime (ms, mean +- stddev, $REPEAT runs)"
    echo
    echo "| Workload | base | asan_default | ratio | asan_paper | ratio |"
    echo "| --- | --- | --- | --- | --- | --- |"
} > "$OUT"

for mode in $MODES; do
    read -r btm bts <<< "$(stats "$mode" base 4)"
    read -r dtm dts <<< "$(stats "$mode" asan_default 4)"
    read -r ptm pts <<< "$(stats "$mode" asan_paper 4)"
    printf '| `%s` | %s ± %s | %s ± %s | **%sx** | %s ± %s | **%sx** |\n' \
        "$mode" "$btm" "$bts" "$dtm" "$dts" "$(ratio "$dtm" "$btm")" \
        "$ptm" "$pts" "$(ratio "$ptm" "$btm")" >> "$OUT"
done

{
    echo
    echo "### Table 1b  Measurement noise (coefficient of variation = stddev / mean)"
    echo
    echo "| Workload | base | asan_default | asan_paper |"
    echo "| --- | --- | --- | --- |"
} >> "$OUT"

for mode in $MODES; do
    read -r btm bts <<< "$(stats "$mode" base 4)"
    read -r dtm dts <<< "$(stats "$mode" asan_default 4)"
    read -r ptm pts <<< "$(stats "$mode" asan_paper 4)"
    printf '| `%s` | %s%% | %s%% | %s%% |\n' "$mode" "$(cv "$btm" "$bts")" "$(cv "$dtm" "$dts")" "$(cv "$ptm" "$pts")" >> "$OUT"
done

{
    echo
    echo "## Table 2  Memory (VmHWM, KB, mean +- stddev, $REPEAT runs)"
    echo
    echo "| Workload | base | asan_default | ratio | asan_paper | ratio |"
    echo "| --- | --- | --- | --- | --- | --- |"
} >> "$OUT"

for mode in $MODES; do
    read -r bmm bms <<< "$(stats "$mode" base 5)"
    read -r dmm dms <<< "$(stats "$mode" asan_default 5)"
    read -r pmm pms <<< "$(stats "$mode" asan_paper 5)"
    printf '| `%s` | %s ± %s | %s ± %s | **%sx** | %s ± %s | **%sx** |\n' \
        "$mode" "$bmm" "$bms" "$dmm" "$dms" "$(ratio "$dmm" "$bmm")" \
        "$pmm" "$pms" "$(ratio "$pmm" "$bmm")" >> "$OUT"
done

{
    echo
    echo "## Table 3  Binary size"
    echo
    echo "Corresponds to paper section 4: 1.5x-3.2x on SPEC CPU2006, 2.5x on average."
    echo
    echo "| Build | File | Bytes | Ratio |"
    echo "| --- | --- | --- | --- |"
    echo "| base | build/bench_base | $sz_base | 1.00x |"
    echo "| asan | build/bench_asan | $sz_asan | **${sz_ratio}x** |"
    echo
    echo "## How to read this"
    echo
    echo "1. **The primary memory metric is VmHWM, not the paper's VmPeak**: ASan's shadow"
    echo "   memory is a \`MAP_NORESERVE\` virtual reservation, so VmPeak is inflated to about"
    echo "   20 TB and no ratio can be derived from it. The 3.37x of the 2012 paper reflects"
    echo "   a real growth in resident memory."
    echo "2. **The gap between the two ASan columns comes mainly from the quarantine**:"
    echo "   \`quarantine=0\` returns freed memory at once, while the default 256MB inflates"
    echo "   the ratio of \`malloc_heavy\` substantially. The paper switched the quarantine off"
    echo "   when measuring performance, so **the asan_paper column is the one comparable"
    echo "   with the paper**."
    echo "3. The workloads are hand-written microbenchmarks, not SPEC CPU2006, so absolute"
    echo "   values cannot be compared with 73% / 3.37x directly; what is comparable is the"
    echo "   order of magnitude and the trend."
    echo
    echo "## How to reproduce"
    echo
    echo '```'
    echo "bash bench/run_bench.sh"
    echo "single run: ASAN_OPTIONS=$PAPER_OPTS ./build/bench_asan malloc_heavy"
    echo '```'
} >> "$OUT"

echo "results written to $OUT"
echo "raw data written to $RAW"
tail -20 "$OUT"
